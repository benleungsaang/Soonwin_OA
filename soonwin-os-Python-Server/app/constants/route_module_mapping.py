# 自动匹配模块名的装饰器
def auto_module_permission(permission_type="view"):
    """自动匹配路由对应的模块名"""
    def decorator(f):
        @wraps(f)
        def decorated_function(*args, **kwargs):
            # 1. 获取当前请求的路由
            path = request.path
            
            # 2. 匹配模块名（简化版，可根据实际路由规则优化）
            module_name = None
            for route_pattern, mod in ROUTE_MODULE_MAP.items():
                if path.startswith(route_pattern.split("<")[0]):
                    module_name = mod
                    break
            
            if not module_name:
                return jsonify({"code": 403, "msg": "未配置该接口的权限模块"}), 403
            
            # 3. 调用模块权限验证逻辑
            from app.utils.auth_utils import require_module_permission
            return require_module_permission(module_name, permission_type)(f)(*args, **kwargs)
        return decorated_function
    return decorator